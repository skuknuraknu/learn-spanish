    /** @return array<string, array{0:string,1:string,2:string}> */
    public static function words(): array
    {
        $out = [];
        foreach (self::raw() as $line) {
            [$word, $literal, $pos, $note] = explode('|', $line, 4);
            $out[$word] = [$literal, self::POS[$pos], $note];
        }

        return $out;
    }

